SELECT
    sub.value:DOCCODE::VARCHAR         AS DOCCODE,
    sub.value:SUPNAME::VARCHAR         AS SUPNAME,
    sub.value:APPCONTREDUCTIONS::FLOAT AS APPCONTREDUCTIONS,
    SOURCE_DB::STRING                  AS SOURCE_DB,
    project.value:DOCNO::VARCHAR       AS DOCNO,
    project.value:CONDATE::DATE        AS CONDATE

FROM {{ source('json', 'BUD_APPCONTREDUCTD_SUBFORM') }},
LATERAL FLATTEN(INPUT => DATA) project,
LATERAL FLATTEN(INPUT => project.value:BUD_FORCASTCONDITION_SUBFORM:BUD_APPCONTREDUCTD_SUBFORM) sub