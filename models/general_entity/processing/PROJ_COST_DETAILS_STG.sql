SELECT
    UNITNAME         as UNIT_OF_MEASURE,
    SONQUANT         as QUANTITY,
    PURCHASEPRICE    as UNIT_COST,
    TOTPURCHASEPRICE as TOTAL_COST,
    SUBCHAPTERNAME   as SUB_CHAPTER_NAME,
    SUBTOPICNAME     as SUB_TOPIC_NAME,
    DOCNO            as PROJECT_NAME,
    CONDATE          as BUD_CONTROL_DATE,
    CASE WHEN TOPICNAME = '013' THEN 'בטון'
         WHEN TOPICNAME = '265' THEN 'ברזל'
        WHEN SUBTOPICNAME IN ('402150', '402100') THEN 'משאבות'
    ELSE NULL END AS RESOURCE_CATEGORY,
    SOURCE_DB
FROM {{ ref('BUD_PROJSECTCOSTC_J') }}