
with control_periods as ( --חודש הבקרה הראשון לכל פרויקט
    select
        "מספר פרויקט",
        "חברה",
        min("Date") as "חודש בקרה ראשון"
    from {{ ref('PROJ_BUDGET_CONTROL_V') }}

    where "Date" is not null and "חודש בקרה" <> 'TODAY'
    group by 1, 2
),

cost_details as ( --פירוט עלויות לפי משאב וחודש בקרה
    select
        "מספר פרויקט",
        "חברה",
        "Date",
        "חודש בקרה",
        "מספר תת פרק",
        "מספר משאב",
        case when "מספר משאב" = '102290' then 'ברזל' else "קטגוריית משאב" end as "קטגוריית משאב",
        "יחידת מידה",
        "כמות",
        "עלות ליחידה",
        "סך הכל עלות"
    from {{ ref('PROJ_COST_DETAILS_V_Budget_Control') }}

    where "קטגוריית משאב" in ('בטון', 'ברזל', 'משאבות') or "מספר משאב" = '102290'
),

budget_classification as ( --זיהוי תקציב ראשון ותקציב TODAY
    select
        c.*,
        iff(c."Date" = p."חודש בקרה ראשון" and c."חודש בקרה" <> 'TODAY', 1, 0) as "דגל תקציב 0",
        iff(c."חודש בקרה" = 'TODAY', 1, 0) as "דגל תקציב מעודכן",
        iff(c."מספר משאב" in ( --החרגת תוספות בטון + חיתוך וכיפוף ברזל
        '102190',
        '102191',
        '102195',
        '102290'), 1, 0) as "דגל תוספות"
    from cost_details c

    left join control_periods p
        on c."מספר פרויקט" = p."מספר פרויקט"
       and c."חברה" = p."חברה"
),

budget_agg as ( --סיכום תקציב מהדורת אפס ותקציב מעודכן
    select
        "מספר פרויקט",
        "חברה",
        "מספר תת פרק",
        "מספר משאב",
        max("קטגוריית משאב") as "קטגוריית משאב",
        -- תקציב מהדורת אפס
        max(iff("דגל תקציב 0" = 1, "יחידת מידה", null)) as "יחידת מידה תקציב 0",
        sum(iff("דגל תקציב 0" = 1 and "דגל תוספות" = 0, coalesce("כמות", 0), 0)) as "כמות תקציב 0",
        max(iff("דגל תקציב 0" = 1 and "דגל תוספות" = 0, "עלות ליחידה", null)) as "מחיר ליחידה תקציב 0",
        sum(iff("דגל תקציב 0" = 1, coalesce("סך הכל עלות", 0), 0)) as "סהכ עלות תקציב 0",
        -- כמויות מעודכנות TODAY
        max(iff("דגל תקציב מעודכן" = 1, "יחידת מידה", null)) as "יחידת מידה מעודכנת",
        sum(iff("דגל תקציב מעודכן" = 1 and "דגל תוספות" = 0, coalesce("כמות", 0), 0)) as "כמות מעודכנת",
        max(iff("דגל תקציב מעודכן" = 1 and "דגל תוספות" = 0, "עלות ליחידה", null)) as "מחיר ליחידה מעודכן",
        sum(iff("דגל תקציב מעודכן" = 1, coalesce("סך הכל עלות", 0), 0)) as "סהכ עלות מעודכנת"
    from budget_classification

    where "דגל תקציב 0" = 1 or "דגל תקציב מעודכן" = 1
    group by 1, 2, 3, 4
),

actual_expenses as ( --נתוני ביצוע בפועל
    select
        "מספר פרויקט",
        "חברה",
        "מספר תת פרק",
        "מספר משאב",
        "יח' מפעל",
        "כמות בתעודה",
        "סכום",
        iff("מספר משאב" in ( --החרגת תוספות בטון + חיתוך וכיפוף ברזל
        '102190',
        '102191',
        '102195',
        '102290'), 1, 0) as "דגל תוספות"
    from {{ ref('PROJ_ACTUAL_EXPENSES_V_Budget_Control') }}
    where control_month = 'TODAY'
),

actual_agg as ( --סיכום ביצוע בפועל לפי פרויקט ומשאב
    select
        "מספר פרויקט",
        "חברה",
        "מספר תת פרק",
        "מספר משאב",
        max("יח' מפעל") as "יחידת מידה בפועל",
        -- כמות ללא תוספות
        sum(iff("דגל תוספות" = 0, coalesce("כמות בתעודה", 0), 0)) as "כמות בפועל",
        -- סכום כולל תוספות
        sum(coalesce("סכום", 0)) as "סהכ בפועל",
        -- סכום ללא תוספות
        sum(iff("דגל תוספות" = 0, coalesce("סכום", 0), 0)) as "סהכ בפועל ללא תוספות"
    from actual_expenses
    group by 1, 2, 3, 4
),

resource_categories as (
    select
        "מספר פרויקט",
        "חברה",
        "מספר תת פרק",
        "מספר משאב",
        max(
            case when "מספר משאב" = '102290' then 'ברזל'
                 when "מספר משאב" in ('402150', '402100') then 'משאבות'
                 when "מספר נושא" = '013' then 'בטון'
                 when "מספר נושא" = '265' then 'ברזל'
                 else null end) as "קטגוריית משאב"
    from {{ ref('PROJ_BUD_EXP_FORECAST_V') }}
    group by 1, 2, 3, 4
),

all_resources as ( --כל המשאבים מהתקציב ומהביצוע בפועל
    select
        "מספר פרויקט",
        "חברה",
        "מספר תת פרק",
        "מספר משאב"
    from budget_agg

    union

    select
        "מספר פרויקט",
        "חברה",
        "מספר תת פרק",
        "מספר משאב"
    from actual_agg
),

report_base as ( --חיבור הנתונים לשורה אחת לכל משאב
    select
        r."מספר פרויקט",
        r."חברה",
        r."מספר תת פרק",
        r."מספר משאב",
        coalesce(b."קטגוריית משאב", d."קטגוריית משאב") as "קטגוריית משאב",
        -- תקציב מהדורת אפס
        b."יחידת מידה תקציב 0",
        coalesce(b."כמות תקציב 0", 0) as "כמות תקציב 0",
        b."מחיר ליחידה תקציב 0",
        coalesce(b."סהכ עלות תקציב 0", 0) as "סהכ עלות תקציב 0",
        -- כמויות מעודכנות
        b."יחידת מידה מעודכנת",
        coalesce(b."כמות מעודכנת", 0) as "כמות מעודכנת",
        b."מחיר ליחידה מעודכן",
        coalesce(b."סהכ עלות מעודכנת", 0) as "סהכ עלות מעודכנת",
        -- שינוי
        coalesce(b."כמות מעודכנת", 0) - coalesce(b."כמות תקציב 0", 0) as "שינוי בכמות",
        coalesce(b."סהכ עלות מעודכנת", 0) - coalesce(b."סהכ עלות תקציב 0", 0) as "שינוי בשח",
        -- ביצוע בפועל
        a."יחידת מידה בפועל",
        coalesce(a."כמות בפועל", 0) as "כמות בפועל",
        a."סהכ בפועל ללא תוספות" / nullif(a."כמות בפועל", 0) as "מחיר ממוצע בפועל",
        coalesce(a."סהכ בפועל", 0) as "סהכ בפועל",
        -- יתרת צריכה
        coalesce(b."כמות מעודכנת", 0) - coalesce(a."כמות בפועל", 0) as "יתרת כמות",
        coalesce(b."סהכ עלות מעודכנת", 0) - coalesce(a."סהכ בפועל ללא תוספות", 0) as "יתרת שח"
    from all_resources r

    left join budget_agg b
        on r."מספר פרויקט" = b."מספר פרויקט"
       and r."חברה" = b."חברה"
       and r."מספר תת פרק" = b."מספר תת פרק"
       and r."מספר משאב" = b."מספר משאב"

    left join actual_agg a
        on r."מספר פרויקט" = a."מספר פרויקט"
       and r."חברה" = a."חברה"
       and r."מספר תת פרק" = a."מספר תת פרק"
       and r."מספר משאב" = a."מספר משאב"

    left join resource_categories d
        on r."מספר פרויקט" = d."מספר פרויקט"
       and r."חברה" = d."חברה"
       and r."מספר תת פרק" = d."מספר תת פרק"
       and r."מספר משאב" = d."מספר משאב"
),

metric_columns as ( --הגדרת הכותרות והסדר בפיבוט
    select
        column1 as "סדר קבוצה",
        column2 as "קבוצת מדד",
        column3 as "סדר מדד",
        column4 as "שם מדד"

    from values
        (1, 'תקציב מהדורת אפס', 1, 'יחידת מידה'),
        (1, 'תקציב מהדורת אפס', 2, 'כמות'),
        (1, 'תקציב מהדורת אפס', 3, 'מחיר ליחידה'),
        (1, 'תקציב מהדורת אפס', 4, 'סה"כ בש"ח'),

        (2, 'כמויות מעודכנות', 1, 'כמות'),
        (2, 'כמויות מעודכנות', 2, 'מחיר ליחידה'),
        (2, 'כמויות מעודכנות', 3, 'סה"כ בש"ח'),

        (3, 'שינוי', 1, 'כמות'),
        (3, 'שינוי', 2, 'ש"ח'),

        (4, 'בפועל', 1, 'יחידת מידה'),
        (4, 'בפועל', 2, 'כמות'),
        (4, 'בפועל', 3, 'מחיר ממוצע'),
        (4, 'בפועל', 4, 'סה"כ בש"ח'),

        (5, 'יתרת צריכה', 1, 'כמות'),
        (5, 'יתרת צריכה', 2, 'ש"ח')
),

pivot_data as ( --יצירת שורה לכל מדד לצורך הפיבוט
    select
        b."מספר פרויקט",
        b."חברה",
        b."מספר תת פרק",
        b."מספר משאב",
        b."קטגוריית משאב",

        m."סדר קבוצה",
        m."קבוצת מדד",
        m."סדר מדד",
        m."שם מדד",
    case
    -- תקציב מהדורת אפס
    when m."סדר קבוצה" = 1 and m."סדר מדד" = 2 then b."כמות תקציב 0"
    when m."סדר קבוצה" = 1 and m."סדר מדד" = 3 then b."מחיר ליחידה תקציב 0"
    when m."סדר קבוצה" = 1 and m."סדר מדד" = 4 then b."סהכ עלות תקציב 0"
    -- כמויות מעודכנות
    when m."סדר קבוצה" = 2 and m."סדר מדד" = 1 then b."כמות מעודכנת"
    when m."סדר קבוצה" = 2 and m."סדר מדד" = 2 then b."מחיר ליחידה מעודכן"
    when m."סדר קבוצה" = 2 and m."סדר מדד" = 3 then b."סהכ עלות מעודכנת"
    -- שינוי
    when m."סדר קבוצה" = 3 and m."סדר מדד" = 1 then b."שינוי בכמות"
    when m."סדר קבוצה" = 3 and m."סדר מדד" = 2 then b."שינוי בשח"
    -- בפועל
    when m."סדר קבוצה" = 4 and m."סדר מדד" = 2 then b."כמות בפועל"
    when m."סדר קבוצה" = 4 and m."סדר מדד" = 3 then b."מחיר ממוצע בפועל"
    when m."סדר קבוצה" = 4 and m."סדר מדד" = 4 then b."סהכ בפועל"
    -- יתרת צריכה
    when m."סדר קבוצה" = 5 and m."סדר מדד" = 1 then b."יתרת כמות"
    when m."סדר קבוצה" = 5 and m."סדר מדד" = 2 then b."יתרת שח" else null end as "ערך מדד",

    case 
    when m."סדר קבוצה" = 1 and m."סדר מדד" = 1 then b."יחידת מידה תקציב 0"
    when m."סדר קבוצה" = 4 and m."סדר מדד" = 1 then b."יחידת מידה בפועל" else null end as "ערך טקסט"
    from report_base b
    cross join metric_columns m
    where b."קטגוריית משאב" in ('בטון', 'ברזל', 'משאבות')
)

select *
from pivot_data
